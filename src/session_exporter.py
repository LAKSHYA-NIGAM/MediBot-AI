"""
MediBot Clinical Session History Exporter
Exports patient chat transcripts to JSON, Markdown, or CSV format
for clinical documentation and doctor review.
"""

import csv
import io
import json
from datetime import datetime, timezone
from typing import Dict, List, Optional


class SessionExporter:
    @classmethod
    def to_markdown(cls, session_id: str, messages: List[Dict], patient_id: Optional[str] = None) -> str:
        """Formats conversation into a structured markdown report for medical review."""
        lines = [
            "# MediBot-AI Clinical Consultation Transcript",
            f"**Session ID:** `{session_id}`",
            f"**Patient ID:** `{patient_id or 'Anonymous'}`",
            f"**Exported At:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
            f"**Total Exchanges:** {len(messages)}",
            "",
            "---",
            "",
            "## Consultation Log",
            ""
        ]

        for idx, msg in enumerate(messages, 1):
            role = msg.get("role", "user").capitalize()
            content = msg.get("content", "").strip()
            ts = msg.get("timestamp", "N/A")
            lines.append(f"### {idx}. {role} ({ts})")
            lines.append(content)
            lines.append("")

        lines.extend([
            "---",
            "*Disclaimer: This transcript was generated by MediBot-AI and must be reviewed by a qualified healthcare professional before taking clinical action.*"
        ])

        return "\n".join(lines)

    @classmethod
    def to_json(cls, session_id: str, messages: List[Dict], patient_id: Optional[str] = None) -> str:
        """Serializes session into JSON payload."""
        data = {
            "session_id": session_id,
            "patient_id": patient_id,
            "exported_at": datetime.now(timezone.utc).isoformat(),
            "message_count": len(messages),
            "messages": messages
        }
        return json.dumps(data, indent=2)

    @classmethod
    def to_csv(cls, messages: List[Dict]) -> str:
        """Serializes session messages into tabular CSV format."""
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(["index", "role", "timestamp", "content"])

        for idx, msg in enumerate(messages, 1):
            writer.writerow([
                idx,
                msg.get("role", "user"),
                msg.get("timestamp", ""),
                msg.get("content", "").replace("\n", " ")
            ])

        return output.getvalue()
